const UPDATE_META_KEY = "vcWebUpdateMeta";
const UPDATE_CODE_KEY = "vcWebUpdateCode";
const UPDATE_CSS_KEY = "vcWebUpdateCss";

/**
 * Generates the prelude prepended to the extension bundle. It runs in the
 * MAIN world at document_start, before any Discord script: when the in-app
 * Updater downloaded a newer build into sessionStorage, the downloaded build
 * takes the packaged build's place and the packaged bundle never boots.
 * @type {(version: string, buildTimestamp: number) => string}
 */
function makeExtensionUpdateBanner(version, buildTimestamp) {
    return `
// generated by scripts/build/buildWeb.mjs — in-app update swap prelude
(function () {
    var packagedVersion = ${JSON.stringify(version)};
    var packagedHash = ${JSON.stringify(gitHash)};
    var packagedTimestamp = ${JSON.stringify(Number(buildTimestamp))};

    var meta = null, code = null;
    try {
        meta = JSON.parse(sessionStorage.getItem(${JSON.stringify(UPDATE_META_KEY)}) || "null");
        code = sessionStorage.getItem(${JSON.stringify(UPDATE_CODE_KEY)});
    } catch (err) {
        meta = null;
        code = null;
    }

    if (meta == null || typeof code !== "string" || code.length === 0) return;

    // always consume the stored update so a stale one can never be applied twice
    try {
        sessionStorage.removeItem(${JSON.stringify(UPDATE_META_KEY)});
        sessionStorage.removeItem(${JSON.stringify(UPDATE_CODE_KEY)});
    } catch (err) { }

    if (meta.hash === packagedHash) return; // same build, nothing to apply

    function parseVersion(v) {
        return String(v == null ? "" : v).split(".").map(function (n) {
            return parseInt(n, 10) || 0;
        });
    }
    function compareVersions(a, b) {
        var left = parseVersion(a), right = parseVersion(b);
        for (var i = 0; i < Math.max(left.length, right.length); i++) {
            var diff = (left[i] || 0) - (right[i] || 0);
            if (diff !== 0) return diff > 0 ? 1 : -1;
        }
        return 0;
    }

    var storedNewer = compareVersions(meta.version, packagedVersion) > 0
        || (compareVersions(meta.version, packagedVersion) === 0 && (Number(meta.timestamp) || 0) > packagedTimestamp);
    if (!storedNewer) return; // the packaged build is at least as new

    try {
        (0, eval)(code);
    } catch (err) {
        console.error("Equicord: failed to run the downloaded update, booting the packaged build instead", err);
        return;
    }

    // The downloaded build booted. Abort this script so the packaged
    // bundle that follows never runs (would double every patch).
    throw "Equicord: started the downloaded update";
})();
`;
}

